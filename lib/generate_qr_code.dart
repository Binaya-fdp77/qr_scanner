import 'dart:typed_data';
import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:qr_flutter/qr_flutter.dart';
import 'package:gal/gal.dart';

// NOTE: Add these to your pubspec.yaml dependencies:
//   gal: ^2.3.0
//
// gal handles gallery permissions internally on both Android & iOS,
// but make sure you add the required permission entries to
// AndroidManifest.xml / Info.plist as described in the gal package docs.

class GenerateQRCode extends StatefulWidget {
  const GenerateQRCode({super.key});

  @override
  State<GenerateQRCode> createState() => _GenerateQRCodeState();
}

class _GenerateQRCodeState extends State<GenerateQRCode> {
  final TextEditingController controller = TextEditingController();
  bool isSaving = false;

  Future<void> saveQRCode() async {
    if (controller.text.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Enter some data and generate a QR code first')),
      );
      return;
    }

    setState(() => isSaving = true);

    try {
      // Render the QR code to an image using QrPainter directly,
      // so the saved file matches exactly what's on screen.
      final qrValidationResult = QrValidator.validate(
        data: controller.text,
        version: QrVersions.auto,
        errorCorrectionLevel: QrErrorCorrectLevel.L,
      );

      if (qrValidationResult.status != QrValidationStatus.valid) {
        throw Exception('Invalid QR data');
      }

      final qrCode = qrValidationResult.qrCode!;
      final painter = QrPainter.withQr(
        qr: qrCode,
        color: const Color(0xFF000000),
        emptyColor: const Color(0xFFFFFFFF),
        gapless: true,
      );

      final ByteData? byteData =
          await painter.toImageData(1024, format: ui.ImageByteFormat.png);

      if (byteData == null) {
        throw Exception('Failed to render QR code image');
      }

      final Uint8List pngBytes = byteData.buffer.asUint8List();

      await Gal.putImageBytes(
        pngBytes,
        name: 'qr_code_${DateTime.now().millisecondsSinceEpoch}',
      );

      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('QR code saved to gallery!')),
      );
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('Failed to save QR code: $e')),
      );
    } finally {
      if (mounted) setState(() => isSaving = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Generate QR Code')),
      body: Center(
        child: SingleChildScrollView(
          child: Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              if (controller.text.isNotEmpty) ...[
                QrImageView(
                  data: controller.text,
                  size: 200,
                ),
                const SizedBox(height: 6),
                const Text(
                  'Generated by @binaya',
                  style: TextStyle(
                    fontSize: 11,
                    color: Colors.grey,
                    fontStyle: FontStyle.italic,
                  ),
                ),
              ],
              const SizedBox(height: 20),
              Padding(
                padding: const EdgeInsets.symmetric(horizontal: 20),
                child: TextField(
                  controller: controller,
                  decoration: const InputDecoration(
                    labelText: 'Enter Your Data',
                    border: OutlineInputBorder(),
                  ),
                ),
              ),
              const SizedBox(height: 20),
              ElevatedButton(
                onPressed: () {
                  setState(() {});
                },
                child: const Text('Generate QR Code'),
              ),
              const SizedBox(height: 12),
              ElevatedButton.icon(
                onPressed: isSaving ? null : saveQRCode,
                icon: isSaving
                    ? const SizedBox(
                        width: 16,
                        height: 16,
                        child: CircularProgressIndicator(strokeWidth: 2),
                      )
                    : const Icon(Icons.download),
                label: Text(isSaving ? 'Saving...' : 'Download QR Code'),
                style: ElevatedButton.styleFrom(
                  backgroundColor: Colors.green,
                  foregroundColor: Colors.white,
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
